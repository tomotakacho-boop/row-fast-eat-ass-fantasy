create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, display_name, avatar_url)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(coalesce(new.email, 'League member'), '@', 1)),
    new.raw_user_meta_data ->> 'avatar_url'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create or replace function public.stamp_post_author()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare member public.profiles%rowtype;
begin
  select * into member from public.profiles where id = new.user_id;
  new.author_name := member.display_name;
  new.author_avatar := member.avatar_url;
  new.author_team_id := member.team_id;
  new.author_team_name := member.team_name;
  return new;
end;
$$;

drop trigger if exists stamp_feed_post_author on public.feed_posts;
create trigger stamp_feed_post_author
  before insert or update on public.feed_posts
  for each row execute procedure public.stamp_post_author();

