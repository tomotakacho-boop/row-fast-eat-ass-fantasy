create or replace function public.is_allowed_league_member()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select
    not exists (select 1 from public.allowed_members where active = true)
    or exists (
      select 1 from public.allowed_members
      where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
        and active = true
    );
$$;

grant execute on function public.is_allowed_league_member() to authenticated;

drop policy if exists "members read profiles" on public.profiles;
